import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { resolveScreenRequest } from "./resolve-screen-request.mjs";
import { generateScreenTsx } from "./generate-screen-tsx.mjs";
import { auditScreenImplementation } from "./audit-screen-implementation.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export function slideExampleRequests() {
  const requests = JSON.parse(readFileSync(resolve(root, "src/design-system/registry/slide-composition-examples.json"), "utf8")).requests;
  for (const [suffix, methods] of [["blank", ["blank-row"]], ["staged", ["entry-form"]]]) {
    const request = structuredClone(requests.find(r => r.generation.templateId === "side-slide-entry-list.v1"));
    request.requestId += "-" + suffix;
    request.output.route = "/preview/" + request.requestId;
    request.output.componentName = suffix === "blank" ? "BlankRowsExample" : "StagedEntryExample";
    const list = request.generation.sections.find(s => s.kind === "record-list");
    list.addMethods = methods;
    if (suffix === "blank") request.generation.sections = request.generation.sections.filter(s => s.kind !== "entry-form");
    else list.editableFields = [];
    requests.push(request);
  }
  return requests;
}
export function syncSlideExamples(write = false) {
  for (const request of slideExampleRequests()) {
    const contract = resolveScreenRequest(request);
    const source = "// Generated by sync-slide-composition-examples.mjs. Edit the request/model, not this file.\n" + generateScreenTsx(contract);
    const audit = auditScreenImplementation(contract, source);
    if (audit.blockerCount) throw new Error(JSON.stringify(audit.findings));
    const path = resolve(root, "src/components/visual-tests/slide-compositions", request.output.componentName + ".tsx");
    if (write) { mkdirSync(dirname(path), { recursive: true }); writeFileSync(path, source); }
    else if (!existsSync(path) || readFileSync(path, "utf8") !== source) throw new Error("조합 예제가 요청/생성기와 다릅니다: " + path);
  }
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  syncSlideExamples(process.argv.includes("--write"));
  console.log("Slide composition examples checked.");
}
